import asyncio
import json
import os
import sqlite3
import threading
from typing import Any, Dict, Iterator, Optional, Tuple


class CardRepository:
    """
    Unifies two card backing stores behind one dict-like interface, so the
    rest of the application (app.py) can read a card via `.get()`, `in`,
    `[...]`, or `.items()` without needing to know or care whether that
    particular card is ephemeral or persistent.

    - Ephemeral cards (the default) live only in `self._memory`, a plain
      dict bounded by `max_memory_cards` with oldest-first eviction. They
      never touch disk and disappear on restart, exactly like the
      original MemoryDB behavior before persistence existed.

    - Persistent cards are explicitly requested at generation time
      (`persistent=True`) and are written to a small SQLite file (stdlib
      only, no new dependency, no separate service). Lookups are lazy:
      persistent cards are *not* eagerly loaded into an in-memory cache
      at startup or on every write, so this never becomes a full
      duplicate copy of the persistent database sitting in RAM - each
      get()/contains() check queries SQLite directly by primary key
      (fast; it's a simple indexed lookup), and only a listing operation
      (`items()`, `by_game_id()`) does a full table scan, on demand.

    A card's identity (`public_id`) is never regenerated by this class:
    callers compute it once (see logic/cards.py's short_id) and this
    class only ever stores/retrieves under that exact key, whichever
    store it lives in.
    """

    def __init__(
        self,
        max_memory_cards: int = 25000,
        max_persistent_cards: int = 100000,
        card_db_path: Optional[str] = None,
    ):
        self._memory: Dict[str, Dict[str, Any]] = {}
        self.max_memory_cards = max_memory_cards
        self.max_persistent_cards = max_persistent_cards

        # ":memory:" (used by default in tests, see conftest.py) never
        # touches disk and is fully isolated per-process/per-instance.
        self._db_path = (
            card_db_path
            if card_db_path is not None
            else os.getenv("CARD_DB_PATH", "data/cards.db")
        )
        self._db_lock = threading.Lock()
        self._conn = self._init_db()

    # -------------------------
    # SQLite (persistent store)
    # -------------------------

    def _init_db(self) -> sqlite3.Connection:
        path = self._db_path
        if path != ":memory:":
            dirname = os.path.dirname(path)
            if dirname:
                os.makedirs(dirname, exist_ok=True)
        # check_same_thread=False: FastAPI runs sync `def` path operations
        # in a thread pool, so lookups can happen off the main thread even
        # though writes currently only ever come from async endpoints on
        # the event loop thread. The lock below serializes actual SQLite
        # access defensively.
        conn = sqlite3.connect(path, check_same_thread=False)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS cards (
                public_id TEXT PRIMARY KEY,
                serial TEXT NOT NULL,
                game_id TEXT,
                grid TEXT NOT NULL,
                owner_id TEXT,
                is_persistent BOOLEAN DEFAULT 1,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
            """)
        # Ensure newer columns exist if migrating from an older database file
        cursor = conn.execute("PRAGMA table_info(cards)")
        existing_cols = {row[1] for row in cursor.fetchall()}
        if "owner_id" not in existing_cols:
            conn.execute("ALTER TABLE cards ADD COLUMN owner_id TEXT")
        if "is_persistent" not in existing_cols:
            conn.execute("ALTER TABLE cards ADD COLUMN is_persistent BOOLEAN DEFAULT 1")
        if "created_at" not in existing_cols:
            conn.execute("ALTER TABLE cards ADD COLUMN created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP")
        conn.commit()
        return conn

    def _persistent_count(self) -> int:
        with self._db_lock:
            (count,) = self._conn.execute("SELECT COUNT(*) FROM cards").fetchone()
        return int(count)

    def _persistent_get(self, public_id: str) -> Optional[Dict[str, Any]]:
        with self._db_lock:
            row = self._conn.execute(
                "SELECT serial, game_id, grid, owner_id FROM cards WHERE public_id = ?",
                (public_id,),
            ).fetchone()
        if row is None:
            return None
        serial, game_id, grid_json, owner_id = row
        return {"serial": serial, "game_id": game_id, "grid": json.loads(grid_json), "owner_id": owner_id}

    def _persistent_contains(self, public_id: str) -> bool:
        with self._db_lock:
            row = self._conn.execute(
                "SELECT 1 FROM cards WHERE public_id = ?", (public_id,)
            ).fetchone()
        return row is not None

    def _persistent_set(self, public_id: str, card_data: Dict[str, Any]) -> None:
        with self._db_lock:
            self._conn.execute(
                "INSERT OR REPLACE INTO cards (public_id, serial, game_id, grid, owner_id) VALUES (?, ?, ?, ?, ?)",
                (
                    public_id,
                    card_data["serial"],
                    card_data.get("game_id"),
                    json.dumps(card_data["grid"]),
                    card_data.get("owner_id"),
                ),
            )
            self._conn.commit()

    def _persistent_items(self) -> Iterator[Tuple[str, Dict[str, Any]]]:
        with self._db_lock:
            rows = self._conn.execute(
                "SELECT public_id, serial, game_id, grid, owner_id FROM cards"
            ).fetchall()
        for public_id, serial, game_id, grid_json, owner_id in rows:
            yield public_id, {
                "serial": serial,
                "game_id": game_id,
                "grid": json.loads(grid_json),
                "owner_id": owner_id,
            }

    # -------------------------
    # Unified read interface
    # -------------------------

    def get(self, public_id: str, default=None) -> Optional[Dict[str, Any]]:
        if public_id in self._memory:
            return self._memory[public_id]
        found = self._persistent_get(public_id)
        return found if found is not None else default

    def __contains__(self, public_id: str) -> bool:
        return public_id in self._memory or self._persistent_contains(public_id)

    def is_persistent(self, public_id: str) -> bool:
        """Whether this card lives in the durable SQLite store (as opposed
        to the ephemeral in-memory store, or not existing at all)."""
        return self._persistent_contains(public_id)

    def __getitem__(self, public_id: str) -> Dict[str, Any]:
        value = self.get(public_id)
        if value is None:
            raise KeyError(public_id)
        return value

    def items(self) -> Iterator[Tuple[str, Dict[str, Any]]]:
        """All cards, ephemeral and persistent. Persistent cards require a
        full table scan; fine for the admin card-listing use case this
        serves, but callers should not call this in a hot path."""
        yield from self._memory.items()
        yield from self._persistent_items()

    def by_owner(self, owner_id: Optional[str]) -> Iterator[Tuple[str, Dict[str, Any]]]:
        """Yield cards belonging to owner_id. If owner_id is None, yield system-owned cards."""
        for public_id, card_data in self.items():
            card_owner = card_data.get("owner_id")
            if card_owner == owner_id:
                yield public_id, card_data

    # -------------------------
    # Writes
    # -------------------------

    def set(
        self, public_id: str, card_data: Dict[str, Any], persistent: bool = False
    ) -> None:
        """Store a card. `persistent=False` (the default) keeps it
        in-memory only - it disappears on restart and never touches disk.
        `persistent=True` writes it to the SQLite-backed store, where it
        survives restarts and is never silently evicted.
        """
        if persistent:
            if (
                not self._persistent_contains(public_id)
                and self._persistent_count() >= self.max_persistent_cards
            ):
                # Persistent storage is explicitly meant to be durable, so
                # we refuse new persistent writes past the cap rather than
                # silently evicting someone's previously-saved card.
                raise PersistentStorageFullError(
                    f"Persistent card storage is at capacity ({self.max_persistent_cards} cards)"
                )
            try:
                self._persistent_set(public_id, card_data)
            except sqlite3.Error as exc:
                # Explicit persistence was requested; fail clearly rather
                # than silently falling back to ephemeral storage, so the
                # caller (and the player relying on this card existing
                # tomorrow) isn't misled into thinking it was saved.
                raise PersistentStorageUnavailableError(
                    f"Persistent card storage is unavailable: {exc}"
                ) from exc
            return

        if len(self._memory) >= self.max_memory_cards and public_id not in self._memory:
            oldest_key = next(iter(self._memory))
            del self._memory[oldest_key]
        self._memory[public_id] = card_data

    def clear(self) -> None:
        """Reset all state, including the on-disk persistent store."""
        self._memory.clear()
        with self._db_lock:
            self._conn.execute("DELETE FROM cards")
            self._conn.commit()

    def close(self) -> None:
        """Close the underlying SQLite connection (mainly for tests)."""
        self._conn.close()

    def __len__(self) -> int:
        return len(self._memory) + self._persistent_count()


class PersistentStorageFullError(RuntimeError):
    """Raised when a request explicitly asks for persistent card storage
    but the persistent store is at its configured capacity. Callers
    should surface this as a clear error to the client rather than
    silently falling back to ephemeral storage."""


class PersistentStorageUnavailableError(RuntimeError):
    """Raised when a request explicitly asks for persistent card storage
    but the underlying SQLite store cannot be written to (e.g. disk full,
    permission denied). Callers should surface this as a clear error to
    the client rather than silently falling back to ephemeral storage."""


class MemoryDB:
    """
    Storage for games and cards.

    Game state (drawn numbers, mode, stage) stays purely in-memory: this
    application runs as a single backend replica, and per the project's
    scope, there is no requirement for a game session to survive a
    restart mid-draw.

    Cards are different: whether a given card should survive a backend
    restart and be reusable across multiple game sessions is an explicit,
    per-request decision (see CardBatchRequest.persistent), not a global
    switch - see CardRepository above for how that's implemented.
    """

    def __init__(
        self,
        max_games: int = 100,
        max_cards: int = 25000,
        max_persistent_cards: int = 100000,
        card_db_path: Optional[str] = None,
    ):
        self.games: Dict[str, Dict[str, Any]] = {}
        self.cards = CardRepository(
            max_memory_cards=max_cards,
            max_persistent_cards=max_persistent_cards,
            card_db_path=card_db_path,
        )
        self._locks: Dict[str, asyncio.Lock] = {}
        self.max_games = max_games
        self.max_cards = max_cards

    def get_lock(self, game_id: str) -> asyncio.Lock:
        """Get or create an asyncio.Lock for a specific game_id to ensure serialized operations."""
        if game_id not in self._locks:
            self._locks[game_id] = asyncio.Lock()
        return self._locks[game_id]

    def set_game(self, game_id: str, game_data: Dict[str, Any]) -> None:
        """Store game data with resource bound enforcement (in-memory only)."""
        if len(self.games) >= self.max_games and game_id not in self.games:
            # Evict oldest game if capacity reached
            oldest_key = next(iter(self.games))
            del self.games[oldest_key]
            if oldest_key in self._locks:
                del self._locks[oldest_key]
        self.games[game_id] = game_data

    def get_game_owner(self, game_id: str) -> Optional[str]:
        """Get the owner_id of a game, or None if not found/system-owned."""
        game = self.games.get(game_id)
        if not game:
            return None
        return game.get("owner_id")

    def set_card(
        self, public_id: str, card_data: Dict[str, Any], persistent: bool = False
    ) -> None:
        """Store card data. See CardRepository.set for the persistence
        semantics (`persistent` defaults to False: in-memory/ephemeral,
        matching existing clients that don't specify it)."""
        self.cards.set(public_id, card_data, persistent=persistent)

    def clear(self) -> None:
        """Reset all state, including the on-disk persistent card store."""
        self.games.clear()
        self.cards.clear()
        self._locks.clear()

    def close(self) -> None:
        """Close the underlying SQLite connection (mainly for tests)."""
        self.cards.close()


def _int_env(name: str, default: int) -> int:
    raw = os.getenv(name)
    if raw is None or raw.strip() == "":
        return default
    try:
        return int(raw)
    except ValueError:
        return default


db = MemoryDB(
    max_games=_int_env("MAX_GAMES", 100),
    max_cards=_int_env("MAX_MEMORY_CARDS", 25000),
    max_persistent_cards=_int_env("MAX_PERSISTENT_CARDS", 100000),
)
